import assert from 'node:assert/strict';
import { build } from 'esbuild';

const built = await build({ entryPoints: ['app/lib/output-runs.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { matchingPrevisShot, editedRun, withPrevisBinding, compactCreativePrompt, CREATIVE_PROMPT_LIMIT, withVoiceRoles } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`);
const source = { beat_ids: ['BEAT_006_1'], source_start_seconds: 67.3, source_end_seconds: 83, target_prompt: 'original' };
const shots = [{ index: 6, beatId: 'BEAT_006', start: 67.3, end: 100.6 }];
assert.equal(matchingPrevisShot(source, shots, true)?.index, 6);
assert.equal(matchingPrevisShot(source, shots, false), undefined);
assert.equal(matchingPrevisShot({ ...source, source_end_seconds: 101 }, shots, true), undefined);
assert.equal(matchingPrevisShot({ ...source, beat_ids: ['BEAT_006_1', 'BEAT_007'] }, shots, true), undefined);
assert.equal(editedRun(source, { original: 'original', text: 'edited' }).target_prompt, 'edited');
assert.equal(editedRun(source, { original: 'older', text: 'stale' }).target_prompt, 'original');
assert.equal(source.target_prompt, 'original');
const prompt = '[素材绑定：图片]\n\nCHAR_A = 【角色A图片】\n\nCHAR_B = 【角色B图片】\n\n9.6 秒。只用角色图和以下文字分镜，不需要参考视频。\n\n动作：举手';
const bound = withPrevisBinding(prompt);
assert.ok(bound.indexOf('CHAR_A =') < bound.indexOf('9.6 秒'));
assert.ok(bound.indexOf('CHAR_B =') < bound.indexOf('9.6 秒'));
assert.ok(bound.indexOf('3D 参考 =') < bound.indexOf('9.6 秒'));
assert.ok(bound.endsWith('动作：举手'));
assert.ok(!bound.includes('不需要参考视频'));
assert.equal(withPrevisBinding(bound), bound);
assert.ok(withPrevisBinding('动作：走路').startsWith('3D 参考 ='));
assert.ok(!bound.includes('[素材绑定'));
assert.equal(CREATIVE_PROMPT_LIMIT, 4000);
const compact = compactCreativePrompt(prompt.replace('9.6 秒。', '9.6 秒，9:16。') + '\n\nCHAR_A：冗长外观描述。固定特征：重复外观。身体约束：保持猫科四肢。');
assert.ok(!compact.includes('9:16') && !compact.includes('[素材绑定'));
assert.ok(!compact.includes('冗长外观描述'));
assert.ok(compact.includes('保持猫科四肢') && compact.includes('动作：举手'));
assert.equal(compactCreativePrompt(compact), compact);
const whole = withPrevisBinding(prompt, 'full');
assert.ok(whole.includes('【整片 3D 预演视频】'));
assert.ok(!whole.includes('【本段预演视频】'));
assert.ok(whole.indexOf('3D 参考 =') < whole.indexOf('9.6 秒'));
const roles = [{ character_id: 'CHAR_A', entity_type: 'anthropomorphic_animal', species: '猫', body_plan: '猫科四肢', anthropomorphism_level: 'full' }, { character_id: 'CHAR_B', entity_type: 'animal', species: '狗', body_plan: '犬科四肢', anthropomorphism_level: 'none' }, { character_id: 'CHAR_C', entity_type: 'human', species: '人类', body_plan: '人形', anthropomorphism_level: 'none' }];
const voices = withVoiceRoles('声音：呼喊声\n\n对白：CHAR_C: Stop!', roles, ['CHAR_C']);
assert.ok(voices.includes('CHAR_A：真实猫叫') && voices.includes('CHAR_B：真实犬吠'));
assert.ok(voices.includes('对白只由 CHAR_C') && voices.includes('不发人类喊叫'));
assert.equal(withVoiceRoles(voices, roles, ['CHAR_C']), voices);
assert.ok(!withVoiceRoles('对白：CHAR_A: Hello', roles.slice(0, 1), ['CHAR_A']).includes('不说人话'));
console.log('Output run edits and safe 3D matching passed.');
